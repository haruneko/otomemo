// CPython（3.12・Linux x86_64・glibc 2.39）の浮動小数の計算を最後の桁まで写す小道具。
//
// - pyExp：`math.exp`。V8 の Math.exp は glibc と最後の1桁で食い違う（乱数 30 万点で約 1 割・実測 2026-09-17）。
//   glibc の exp は「正しく丸めた値」でもない（同じ 30 万点で 202 点が最近接でない）ので、倍精度を足しても合わない。
//   → glibc sysdeps/ieee754/dbl-64/e_exp.c のアルゴリズム（表 2^(k/128)・5次多項式）をそのまま写す。
//   母艦の CPU は FMA 対応で glibc は FMA 版（e_exp-fma）を選ぶ＝式の中の「掛けて足す」は FMA（丸め1回）になる。
//   JS に FMA は無いので BigInt で厳密に計算して1回だけ丸める（呼ぶ回数は少ない＝速さは問わない）。
//   検算＝同じ 30 万点で全件一致（FMA なしの式だと 203 点ずれる）。固定の抜粋＝test/fixtures/py-math.json。
//   表の値＝2^(k/128) の最近接 double（H）と (2^(k/128) − H)/H の最近接 double（T）を十進 80 桁で作ったもの。
// - pySum：組み込み `sum()` の浮動小数の足し算。3.12 から補償付き（Neumaier）＝素朴な足し算と最後の桁が違いうる。
//
// 乱数・時刻は使わない（純関数）。

const F64 = new Float64Array(1);
const U64 = new BigUint64Array(F64.buffer);

/** x = m · 2^e（m は符号つき整数）。 */
function decompose(x: number): [bigint, number] {
  if (x === 0) return [0n, 0];
  F64[0] = x;
  const bits = U64[0]!;
  const neg = bits >> 63n === 1n;
  const e = Number((bits >> 52n) & 0x7ffn);
  let m = bits & ((1n << 52n) - 1n);
  let ex: number;
  if (e === 0) ex = -1074;
  else { m |= 1n << 52n; ex = e - 1075; }
  return [neg ? -m : m, ex];
}

/** fma(a, b, c) = a·b + c を1回だけ丸める（IEEE 754 fusedMultiplyAdd・最近接偶数）。有限値の範囲だけ扱う。 */
export function fma(a: number, b: number, c: number): number {
  const [ma, ea] = decompose(a);
  const [mb, eb] = decompose(b);
  const [mc, ec] = decompose(c);
  const mp = ma * mb;
  const ep = ea + eb;
  if (mp === 0n) return a * b + c;
  if (mc === 0n) return a * b;
  const e = Math.min(ep, ec);
  const sum = (mp << BigInt(ep - e)) + (mc << BigInt(ec - e));
  if (sum === 0n) return 0;
  const neg = sum < 0n;
  let mag = neg ? -sum : sum;
  let e2 = e;
  const bitLen = mag.toString(2).length;
  if (bitLen > 200) { // 下の桁を「端数あり」の1ビットに畳む（丸めの向きは変わらない）
    const sh = bitLen - 120;
    const lost = mag & ((1n << BigInt(sh)) - 1n);
    mag = ((mag >> BigInt(sh)) << 1n) | (lost !== 0n ? 1n : 0n);
    e2 += sh - 1;
  }
  const r = Number(mag) * 2 ** e2; // Number(BigInt) は最近接偶数丸め・2 の冪を掛けるのは正確（正規化数の域）
  return neg ? -r : r;
}

