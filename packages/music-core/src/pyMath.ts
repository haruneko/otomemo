/** Python `math.exp(x)`（glibc 2.39・FMA 版）と同じ double。|x| ≥ 512 は検算していないので例外。 */
export function pyExp(x: number): number {
  if (Number.isNaN(x)) return NaN;
  const ax = Math.abs(x);
  if (ax < 2 ** -54) return 1.0 + x;
  if (ax >= 512) throw new Error(`pyExp: |x| >= 512 is outside the verified range (got ${x})`);
  const z = INV_LN2_N * x;
  const kd = Math.sign(z) * Math.round(Math.abs(z)); // C round()＝ちょうど半分は 0 から遠い側
  const r = fma(kd, NEG_LN2_LO_N, fma(kd, NEG_LN2_HI_N, x));
  const k = ((kd % 128) + 128) % 128;
  const scale = EXP_H[k]! * 2 ** ((kd - k) / 128);
  const tail = EXP_T[k]!;
  const r2 = r * r;
  const tmp = fma(r2 * r2, fma(r, C5, C4), fma(r2, fma(r, C3, C2), tail + r));
  return fma(scale, tmp, scale);
}

/** Python 3.12 組み込み `sum(iterable_of_floats)`（start=0・補償付き）。 */
export function pySum(xs: Iterable<number>): number {
  let hi = 0.0;
  let lo = 0.0;
  for (const x of xs) {
    const t = hi + x;
    if (Math.abs(hi) >= Math.abs(x)) lo += (hi - t) + x;
    else lo += (x - t) + hi;
    hi = t;
  }
  if (lo !== 0 && Number.isFinite(lo)) return hi + lo;
  return hi;
}
